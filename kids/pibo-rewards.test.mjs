import assert from 'node:assert/strict';
import {MAX_STARS,normalizeStars,addStars,claimDailyGift,localDay} from './pibo-rewards.mjs';
assert.equal(normalizeStars(-25),0);
assert.equal(normalizeStars(Infinity),0);
assert.equal(normalizeStars('not a number'),0);
assert.equal(normalizeStars(2.8),2);
assert.equal(normalizeStars(1e20),MAX_STARS);
const extras={stars:0,gifts:0,lastGift:''};
assert.equal(addStars(extras,7),7);
assert.equal(addStars(extras,-40),0);
assert.equal(claimDailyGift(extras,'2026-11-01',{stars:5}),true);
assert.equal(claimDailyGift(extras,'2026-11-01',{stars:5}),false);
assert.equal(extras.stars,12);
assert.equal(extras.gifts,1);
assert.equal(claimDailyGift(extras,'invalid',{stars:500}),false);
assert.equal(localDay(new Date(2026,10,1)), '2026-11-01');
extras.stars=MAX_STARS-1;
assert.equal(addStars(extras,20),1);
console.log('PASS: Pibo rewards rules');
